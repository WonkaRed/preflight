pub struct Pf007UnguardedAdmin;

pub static RULE: Pf007UnguardedAdmin = Pf007UnguardedAdmin;

impl Rule for Pf007UnguardedAdmin {
    fn id(&self) -> &'static str {
        "PF007"
    }

    fn title(&self) -> &'static str {
        "Privileged method any account can call"
    }

    fn severity(&self) -> Severity {
        Severity::Critical
    }

    fn help(&self) -> &'static str {
        "check env::predecessor_account_id() against the owner at the top of the method, or mark it #[private]"
    }

    fn check(&self, krate: &Crate) -> Vec<Finding> {
        let mut collector = Collector::default();
        for (index, file) in krate.files.iter().enumerate() {
            collector.file = index;
            collector.visit_file(&file.ast);
        }
        let model = Model::new(collector.fns);
        let guards = Guards::new(krate);

        let mut findings = Vec::new();
        for (id, function) in model.fns.iter().enumerate() {
            let Some(export) = &function.export else { continue };
            if export.init == Init::Constructor || guards.of(function.file, export.span).looks_at_caller() {
                continue;
            }
            let reach = model.reachable(id);
            let mut reasons = Vec::new();
            if export.mut_self {
                reasons.extend(model.written_access_fields(&reach).into_iter().map(|field| {
                    format!("assigns `self.{field}`, which other methods compare with the caller to decide who is in charge")
                }));
            }
            let own_account_ops: BTreeSet<&str> =
                reach.iter().flat_map(|&reached| model.fns[reached].own_account_ops.iter().map(String::as_str)).collect();
            reasons.extend(own_account_ops.into_iter().map(|op| format!("runs `{op}` on the contract's own account")));
            let reads_state = reach.iter().any(|&reached| model.fns[reached].reads_state);
            if export.init == Init::IgnoreState && (reads_state || function.name.contains("migrat")) {
                reasons.push("is `#[init(ignore_state)]`, so anyone can run it again over live state".to_owned());
            }
            if reasons.is_empty() {
                continue;
            }
            let item = format!("{}::{}", function.owner.as_deref().unwrap_or_default(), function.name);
            let message = format!(
                "`{item}` {}, but never checks the caller (no `env::predecessor_account_id()` or \
                 `env::signer_account_id()` on any path from it, and no owner or role check), so any account can call it",
                reasons.join(" and ")
            );
            findings.push(self.finding(&krate.files[function.file], export.span, item, message));
        }
        findings
    }
}

/// `Promise` methods that, aimed at the contract's own account, hand over the contract.
const OWN_ACCOUNT_PROMISE_METHODS: [&str; 6] = [
    "deploy_contract",
    "use_global_contract",
    "use_global_contract_by_account_id",
    "add_full_access_key",
    "add_full_access_key_with_nonce",
    "delete_account",
];

/// `env::promise_batch_action_*` functions with the same effect on the account the batch was created for.
const BATCH_ACTIONS: [&str; 5] = [
    "promise_batch_action_deploy_contract",
    "promise_batch_action_use_global_contract",
    "promise_batch_action_use_global_contract_by_account_id",
    "promise_batch_action_add_key_with_full_access",
    "promise_batch_action_delete_account",
];

/// Methods that change the collection or value they are called on.
const MUTATORS: [&str; 16] = [
    "insert", "remove", "push", "push_back", "push_front", "pop", "extend", "clear", "retain", "set", "replace",
    "take", "swap_remove", "truncate", "append", "drain",
];

const COMPARISON_MACROS: [&str; 4] = ["assert_eq", "assert_ne", "debug_assert_eq", "debug_assert_ne"];

#[derive(Clone, Copy, PartialEq, Eq)]
enum Init {
    No,
    /// `#[init]`: near-sdk panics if the contract is already initialized.
    Constructor,
    /// `#[init(ignore_state)]`: a migration, runs over existing state.
    IgnoreState,
}

/// What the `#[near]` macro exports a method as.
struct Export {
    span: Span,
    init: Init,
    mut_self: bool,
}

enum Caller {
    /// `env::predecessor_account_id()`, or a local that holds it.
    Known,
    /// A plain identifier: the caller only if some call passes the caller for this parameter.
    Param(String),
}

/// `self.<field> == <caller>` (either order) or `self.<field>.contains(<caller>)`.
struct Comparison {
    field: FieldPath,
    caller: Caller,
}

/// One function, method, or crate-local `macro_rules!` of the crate.
#[derive(Default)]
struct FnFacts {
    file: usize,
    /// `name!` for a macro.
    name: String,
    /// The self type of the impl block; `None` for a free function or a macro.
    owner: Option<String>,
    /// Parameter names in order, the receiver as `self`; empty for a pattern that is not a plain identifier.
    inputs: Vec<String>,
    has_receiver: bool,
    export: Option<Export>,
    /// Calls `env::state_read`.
    reads_state: bool,
    calls: Vec<CallRef>,
    /// Calls that pass the caller as an argument: the call and the argument's position.
    caller_args: Vec<(CallRef, usize)>,
    comparisons: Vec<Comparison>,
    writes: Vec<FieldPath>,
    own_account_ops: Vec<String>,
}

/// A function being walked, with the locals that matter to the rule.
#[derive(Default)]
struct Frame {
    facts: FnFacts,
    /// The parameters, the locals computed from one, and the closure parameters.
    derived: BTreeSet<String>,
    caller_locals: BTreeSet<String>,
    current_account_locals: BTreeSet<String>,
    own_account_promises: BTreeSet<String>,
    batch_for_own_account: bool,
    batch_action: Option<&'static str>,
}

impl Frame {
    /// The caller, if `expr` is the caller or a plain identifier that might hold it.
    fn caller_of(&self, expr: &Expr) -> Option<Caller> {
        match peel(expr) {
            Expr::Call(call) if is_call_to(call, &CALLER_FNS) => Some(Caller::Known),
            Expr::MethodCall(call) if call.args.is_empty() && CALLER_FNS.iter().any(|name| call.method == name) => {
                Some(Caller::Known)
            }
            Expr::Path(path) => {
                let name = path.path.get_ident()?.to_string();
                Some(if self.caller_locals.contains(&name) { Caller::Known } else { Caller::Param(name) })
            }
            _ => None,
        }
    }

    /// Whether the node `walk` visits mentions a parameter or a local computed from one.
    fn is_derived(&self, walk: impl FnOnce(&mut Mentions<'_>)) -> bool {
        mentions(&self.derived, walk)
    }

    fn is_current_account(&self, expr: &Expr) -> bool {
        match peel(expr) {
            Expr::Call(call) => is_call_to(call, &["current_account_id"]),
            Expr::Path(path) => path.path.get_ident().is_some_and(|name| self.current_account_locals.contains(&name.to_string())),
            _ => false,
        }
    }

    /// Whether `expr` is a promise aimed at the contract's own account: `Promise::new(<own account>)` with any
    /// actions chained on, or a local that holds one.
    fn targets_own_account(&self, expr: &Expr) -> bool {
        let mut expr = expr;
        loop {
            expr = match expr {
                Expr::MethodCall(call) => &call.receiver,
                Expr::Paren(inner) => &inner.expr,
                Expr::Group(inner) => &inner.expr,
                Expr::Call(call) => {
                    return is_promise_new(call) && call.args.first().is_some_and(|account| self.is_current_account(account));
                }
                Expr::Path(path) => {
                    return path.path.get_ident().is_some_and(|name| self.own_account_promises.contains(&name.to_string()));
                }
                _ => return false,
            };
        }
    }

    /// Notes `env::promise_batch_create(<own account>)` and `env::promise_batch_action_*` calls.
    fn note_batch_call(&mut self, name: Option<&str>, first_argument: Option<&Expr>) {
        match name {
            Some("promise_batch_create") if first_argument.is_some_and(|account| self.is_current_account(account)) => {
                self.batch_for_own_account = true;
            }
            Some(name) => {
                if let Some(action) = BATCH_ACTIONS.iter().find(|action| **action == name) {
                    self.batch_action.get_or_insert(action);
                }
            }
            None => {}
        }
    }

    fn compare(&mut self, left: &Expr, right: &Expr) {
        for (field_side, caller_side) in [(left, right), (right, left)] {
            if let (Some(field), Some(caller)) = (field_path(field_side), self.caller_of(caller_side)) {
                self.facts.comparisons.push(Comparison { field, caller });
            }
        }
    }
}

struct ImplContext {
    owner: String,
    /// The impl carries `#[near]` / `#[near_bindgen]`.
    exports: bool,
    is_trait_impl: bool,
}

#[derive(Default)]
struct Collector {
    file: usize,
    fns: Vec<FnFacts>,
    frames: Vec<Frame>,
    impl_context: Option<ImplContext>,
}

impl Collector {
    fn begin_fn(&mut self, sig: &Signature, attrs: &[Attribute], exported: bool) {
        let inputs = sig
            .inputs
            .iter()
            .map(|arg| match arg {
                FnArg::Receiver(_) => "self".to_owned(),
                FnArg::Typed(arg) => bound_ident(&arg.pat).unwrap_or_default(),
            })
            .collect();
        let derived = sig
            .inputs
            .iter()
            .filter_map(|arg| if let FnArg::Typed(arg) = arg { Some(pattern_idents(&arg.pat)) } else { None })
            .flatten()
            .collect();
        let export = exported.then(|| Export {
            span: sig.ident.span(),
            init: init_kind(attrs),
            mut_self: sig.receiver().is_some_and(|receiver| receiver.reference.is_some() && receiver.mutability.is_some()),
        });
        self.frames.push(Frame {
            facts: FnFacts {
                file: self.file,
                name: sig.ident.to_string(),
                owner: self.impl_context.as_ref().map(|context| context.owner.clone()),
                inputs,
                has_receiver: sig.receiver().is_some(),
                export,
                ..FnFacts::default()
            },
            derived,
            ..Frame::default()
        });
    }

    fn end_fn(&mut self) {
        let Some(Frame { mut facts, batch_for_own_account, batch_action, .. }) = self.frames.pop() else { return };
        if let Some(action) = batch_action.filter(|_| batch_for_own_account) {
            facts.own_account_ops.push(format!("env::{action}"));
        }
        self.fns.push(facts);
    }

    /// Marks the variables `pat` binds as derived when `source` mentions a parameter or a derived local.
    fn bind(&mut self, pat: &Pat, source: &Expr) {
        if let Some(frame) = self.frames.last_mut()
            && frame.is_derived(|search| search.visit_expr(source))
        {
            frame.derived.extend(pattern_idents(pat));
        }
    }

    /// Runs `walk` over a free or trait function, which is never in an impl even when nested inside one.
    fn in_free_fn(&mut self, sig: &Signature, attrs: &[Attribute], walk: impl FnOnce(&mut Self)) {
        let outer = self.impl_context.take();
        self.begin_fn(sig, attrs, false);
        walk(self);
        self.end_fn();
        self.impl_context = outer;
    }
}

impl<'ast> Visit<'ast> for Collector {
    fn visit_item_impl(&mut self, item: &'ast ItemImpl) {
        let context = ImplContext {
            owner: type_name(&item.self_ty),
            exports: item.attrs.iter().any(is_near_attr),
            is_trait_impl: item.trait_.is_some(),
        };
        let outer = self.impl_context.replace(context);
        visit::visit_item_impl(self, item);
        self.impl_context = outer;
    }

    fn visit_impl_item_fn(&mut self, method: &'ast ImplItemFn) {
        let exported = self.impl_context.as_ref().is_some_and(|context| {
            context.exports && (context.is_trait_impl || matches!(method.vis, Visibility::Public(_)))
        });
        self.begin_fn(&method.sig, &method.attrs, exported);
        visit::visit_impl_item_fn(self, method);
        self.end_fn();
    }

    fn visit_item_fn(&mut self, function: &'ast ItemFn) {
        self.in_free_fn(&function.sig, &function.attrs, |this| visit::visit_item_fn(this, function));
    }

    fn visit_trait_item_fn(&mut self, function: &'ast TraitItemFn) {
        self.in_free_fn(&function.sig, &function.attrs, |this| visit::visit_trait_item_fn(this, function));
    }

    fn visit_local(&mut self, local: &'ast Local) {
        if let Some(init) = &local.init {
            self.bind(&local.pat, &init.expr);
        }
        if let (Some(init), Some(name), Some(frame)) = (&local.init, bound_ident(&local.pat), self.frames.last_mut()) {
            if matches!(frame.caller_of(&init.expr), Some(Caller::Known)) {
                frame.caller_locals.insert(name.clone());
            }
            if frame.is_current_account(&init.expr) {
                frame.current_account_locals.insert(name.clone());
            }
            if frame.targets_own_account(&init.expr) {
                frame.own_account_promises.insert(name);
            }
        }
        visit::visit_local(self, local);
    }

    fn visit_expr_for_loop(&mut self, looped: &'ast ExprForLoop) {
        self.bind(&looped.pat, &looped.expr);
        visit::visit_expr_for_loop(self, looped);
    }

    fn visit_expr_let(&mut self, condition: &'ast ExprLet) {
        self.bind(&condition.pat, &condition.expr);
        visit::visit_expr_let(self, condition);
    }

    fn visit_expr_match(&mut self, matched: &'ast ExprMatch) {
        for arm in &matched.arms {
            self.bind(&arm.pat, &matched.expr);
        }
        visit::visit_expr_match(self, matched);
    }

    /// A closure parameter may hold anything its caller hands it, so it counts as derived.
    fn visit_expr_closure(&mut self, closure: &'ast ExprClosure) {
        if let Some(frame) = self.frames.last_mut() {
            frame.derived.extend(closure.inputs.iter().flat_map(pattern_idents));
        }
        visit::visit_expr_closure(self, closure);
    }

    fn visit_expr_call(&mut self, call: &'ast ExprCall) {
        if let Expr::Path(func) = &*call.func {
            let segments: Vec<String> = func.path.segments.iter().map(|segment| segment.ident.to_string()).collect();
            let reference = call_ref(&segments, self.impl_context.as_ref().map(|context| context.owner.as_str()));
            if let Some(frame) = self.frames.last_mut() {
                if let Some(reference) = reference {
                    for (position, argument) in call.args.iter().enumerate() {
                        if matches!(frame.caller_of(argument), Some(Caller::Known)) {
                            frame.facts.caller_args.push((reference.clone(), position));
                        }
                    }
                    frame.facts.calls.push(reference);
                }
                frame.note_batch_call(segments.last().map(String::as_str), call.args.first());
                frame.facts.reads_state |= segments.last().is_some_and(|name| name == "state_read");
            }
        }
        visit::visit_expr_call(self, call);
    }

    fn visit_expr_method_call(&mut self, call: &'ast ExprMethodCall) {
        let name = call.method.to_string();
        if let Some(frame) = self.frames.last_mut() {
            for (position, argument) in call.args.iter().enumerate() {
                if matches!(frame.caller_of(argument), Some(Caller::Known)) {
                    frame.facts.caller_args.push((CallRef::Method(name.clone()), position));
                }
            }
            // The callback of a promise builder runs in a later receipt, and `#[private]` proves only that the contract
            // made the call, not that its arguments are trusted: it is followed when one comes from a parameter.
            let takes_a_parameter =
                frame.is_derived(|search| call.args.iter().for_each(|argument| search.visit_expr(argument)));
            if !starts_a_promise(&call.receiver) || takes_a_parameter {
                frame.facts.calls.push(CallRef::Method(name.clone()));
            }
            if MUTATORS.contains(&name.as_str()) {
                frame.facts.writes.extend(field_path(&call.receiver));
            }
            if matches!(name.as_str(), "contains" | "contains_key")
                && let (Some(field), Some(argument)) = (field_path(&call.receiver), call.args.first())
                && let Some(caller) = frame.caller_of(argument)
            {
                frame.facts.comparisons.push(Comparison { field, caller });
            }
            if OWN_ACCOUNT_PROMISE_METHODS.contains(&name.as_str()) && frame.targets_own_account(&call.receiver) {
                frame.facts.own_account_ops.push(name);
            }
        }
        visit::visit_expr_method_call(self, call);
    }

    fn visit_expr_binary(&mut self, binary: &'ast ExprBinary) {
        if let Some(frame) = self.frames.last_mut() {
            if matches!(binary.op, BinOp::Eq(_) | BinOp::Ne(_)) {
                frame.compare(&binary.left, &binary.right);
            }
            if is_compound_assignment(&binary.op) {
                frame.facts.writes.extend(field_path(&binary.left));
            }
        }
        visit::visit_expr_binary(self, binary);
    }

    fn visit_expr_assign(&mut self, assign: &'ast ExprAssign) {
        if let Some(frame) = self.frames.last_mut() {
            if let Expr::Path(target) = &*assign.left
                && let Some(name) = target.path.get_ident()
                && frame.is_derived(|search| search.visit_expr(&assign.right))
            {
                frame.derived.insert(name.to_string());
            }
            frame.facts.writes.extend(field_path(&assign.left));
        }
        visit::visit_expr_assign(self, assign);
    }

    fn visit_expr_reference(&mut self, reference: &'ast ExprReference) {
        if reference.mutability.is_some()
            && let Some(frame) = self.frames.last_mut()
        {
            frame.facts.writes.extend(field_path(&reference.expr));
        }
        visit::visit_expr_reference(self, reference);
    }

    fn visit_macro(&mut self, mac: &'ast Macro) {
        let Some(name) = mac.path.segments.last().map(|segment| segment.ident.to_string()) else { return };
        // `require!`, `assert!`, `assert_eq!`, `format!` ... take comma-separated expressions: parse and walk them.
        let Ok(arguments) = Punctuated::<Expr, Token![,]>::parse_terminated.parse2(mac.tokens.clone()) else { return };
        if COMPARISON_MACROS.contains(&name.as_str())
            && let (Some(left), Some(right), Some(frame)) = (arguments.first(), arguments.iter().nth(1), self.frames.last_mut())
        {
            frame.compare(left, right);
        }
        for argument in &arguments {
            self.visit_expr(argument);
        }
    }
}

/// The crate's functions with the call graph between them, and the access-control fields.
struct Model {
    fns: Vec<FnFacts>,
    /// For each function, the same-crate functions it may call.
    edges: Vec<Vec<usize>>,
    /// `(impl type, field path)` for every field some function compares with the caller.
    access_fields: BTreeSet<(String, FieldPath)>,
}

impl Model {
    fn new(fns: Vec<FnFacts>) -> Self {
        let resolve = |call: &CallRef| -> Vec<usize> {
            let reaches = |f: &FnFacts| call.reaches(&f.name, f.owner.as_deref(), f.has_receiver);
            fns.iter().enumerate().filter(|(_, f)| reaches(f)).map(|(id, _)| id).collect()
        };
        let edges: Vec<Vec<usize>> = fns.iter().map(|f| f.calls.iter().flat_map(&resolve).collect()).collect();

        // A parameter is the caller when some call passes the caller in its position.
        let mut caller_params = vec![BTreeSet::new(); fns.len()];
        for function in &fns {
            for (call, position) in &function.caller_args {
                let position = if matches!(call, CallRef::Method(_)) { position + 1 } else { *position };
                for target in resolve(call) {
                    if let Some(name) = fns[target].inputs.get(position).filter(|name| !name.is_empty()) {
                        caller_params[target].insert(name.clone());
                    }
                }
            }
        }

        let access_fields = fns
            .iter()
            .enumerate()
            .filter_map(|(id, f)| f.owner.as_ref().map(|owner| (id, owner, f)))
            .flat_map(|(id, owner, f)| {
                let caller_params = &caller_params[id];
                f.comparisons
                    .iter()
                    .filter(move |comparison| match &comparison.caller {
                        Caller::Known => true,
                        Caller::Param(name) => caller_params.contains(name),
                    })
                    .map(move |comparison| (owner.clone(), comparison.field.clone()))
            })
            .collect();
        Self { fns, edges, access_fields }
    }

    /// `id` and every function reachable from it.
    fn reachable(&self, id: usize) -> Vec<usize> {
        let mut seen = vec![id];
        let mut next = 0;
        while let Some(&current) = seen.get(next) {
            next += 1;
            for &callee in &self.edges[current] {
                if !seen.contains(&callee) {
                    seen.push(callee);
                }
            }
        }
        seen
    }

    /// The access-control fields (as `a.b` paths) written by any of `reach`.
    fn written_access_fields(&self, reach: &[usize]) -> BTreeSet<String> {
        let mut written = BTreeSet::new();
        for &id in reach {
            let function = &self.fns[id];
            let Some(owner) = &function.owner else { continue };
            for write in &function.writes {
                let is_access_field = self
                    .access_fields
                    .iter()
                    .any(|(field_owner, field)| field_owner == owner && (field.starts_with(write) || write.starts_with(field)));
                if is_access_field {
                    written.insert(write.join("."));
                }
            }
        }
        written
    }
}

/// `#[near]`, `#[near(..)]` or `#[near_bindgen]`, possibly path-qualified (`#[near_sdk::near]`).
pub(super) fn is_near_attr(attr: &Attribute) -> bool {
    last_segment_is_one_of(attr, &["near", "near_bindgen"])
}

fn init_kind(attrs: &[Attribute]) -> Init {
    match attrs.iter().find(|attr| attr.path().is_ident("init")).map(|attr| &attr.meta) {
        None => Init::No,
        Some(Meta::List(list)) if tokens_contain(&list.tokens, &["ignore_state"]) => Init::IgnoreState,
        Some(_) => Init::Constructor,
    }
}

fn is_promise_new(call: &ExprCall) -> bool {
    matches!(&*call.func, Expr::Path(func) if {
        let mut segments = func.path.segments.iter().rev();
        matches!((segments.next(), segments.next()), (Some(new), Some(promise)) if new.ident == "new" && promise.ident == "Promise")
    })
}

/// Whether a method chain starts a promise, `Promise::new(..)` or `Contract::ext(..)`, so that a method named on it runs
/// in a later receipt (a callback is called by the contract itself) and is no call to this crate's method of that name.
fn starts_a_promise(expr: &Expr) -> bool {
    match expr {
        Expr::Paren(inner) => starts_a_promise(&inner.expr),
        Expr::MethodCall(call) => starts_a_promise(&call.receiver),
        Expr::Call(call) => {
            is_promise_new(call)
                || matches!(&*call.func, Expr::Path(func) if func.path.segments.last().is_some_and(|last| last.ident == "ext"))
        }
        _ => false,
    }
}

pub(super) fn is_compound_assignment(op: &BinOp) -> bool {
    matches!(
        op,
        BinOp::AddAssign(_)
            | BinOp::SubAssign(_)
            | BinOp::MulAssign(_)
            | BinOp::DivAssign(_)
            | BinOp::RemAssign(_)
            | BinOp::BitXorAssign(_)
            | BinOp::BitAndAssign(_)
            | BinOp::BitOrAssign(_)
            | BinOp::ShlAssign(_)
            | BinOp::ShrAssign(_)
    )
}

