//! PF007: a privileged method that any account can call.
//!
//! A contract has a few methods only its owner may call: hand over control, upgrade the code, run a migration.
//! If one of them never looks at who is calling, any account can take the contract over. Docs:
//! https://docs.near.org/smart-contracts/security/one_yocto and the access-control pages beside it.
//!
//! The rule looks at the methods the `#[near]` / `#[near_bindgen]` macro exports (`pub` methods of an inherent
//! impl, every method of a trait impl) and flags one that has no caller check and does any of three things:
//!
//! 1. **Writes an access-control field.** A field of the contract is an access-control field when some method
//!    compares it with the caller: `self.owner == env::predecessor_account_id()` in `require!`, `assert!`,
//!    `assert_eq!`, `if` or a plain expression, directly or through a local (`let caller = ..;`), or
//!    `self.admins.contains(&caller)`. A same-crate helper counts too: in `fn is_owner(&self, account: &AccountId)
//!    -> bool { self.owner == *account }` the parameter is the caller when some call passes it the caller. The rule
//!    flags a `&mut self` method that assigns such a field (`=`, `+=`, a mutating call such as `insert` or `set`,
//!    or `&mut self.field`), itself or through a same-crate helper it calls. Fields are matched by path, so
//!    `self.config.fee` is not `self.config.owner`.
//! 2. **Changes the contract's own account.** `Promise::new(env::current_account_id())` followed by
//!    `.deploy_contract`, `.use_global_contract[_by_account_id]`, `.add_full_access_key[_with_nonce]` or
//!    `.delete_account` (also through a local holding the promise or the account id), or
//!    `env::promise_batch_create(&env::current_account_id())` plus the matching `env::promise_batch_action_*`
//!    in the same function. Deploying to a sub-account or another account is not matched.
//! 3. **Is a migration.** `#[init(ignore_state)]` skips the "already initialized" check, so anyone can re-run it.
//!    Only a method that reads the stored state (`env::state_read()`) or whose name says `migrat..` counts: an
//!    `ignore_state` initializer that never looks at old state is a constructor with a different spelling.
//!
//! A method named on a promise builder (`Promise::new(..)`, `Self::ext(..)` and what is chained to them) runs in a later
//! receipt, so it is followed to the crate's method of that name only when an argument passed to it comes from a
//! parameter of the scheduling method, directly, through a local, a `match`, `for` or `if let` binding, a closure
//! parameter or `format!`. `#[private]` proves only that the contract made
//! the call, not that its arguments are trusted: `Self::ext(..).set_owner_cb(new_owner)` is a write of `owner` by the
//! method that schedules it. A callback handed nothing, constants or contract state is not a write of the scheduler.
//!
//! A method has a caller check when `guards::Guards` says it looks at the caller: it, or a same-crate function it
//! calls, mentions `predecessor_account_id` or `signer_account_id` on every path (even only to log it), or it carries
//! `#[private]` or a near-plugins attribute. No function is trusted by its name: `assert_owner()` counts only through
//! the body of a function the crate defines under that name, so a library's `require_role`, a sibling crate's
//! `assert_owner` or a `use util::noop as assert_owner` guards nothing. The guards module states exactly what is
//! trusted. A normal `#[init]` constructor is never flagged.
//!
//! Knowingly missed: access-control state kept in a nested struct that compares it in its own impl; a field
//! rebound through a local (`let o = &mut self.owner; *o = ..`); a caller reference that only logs the caller
//! (it still counts as a check); ownership generated by `#[derive(Ownable)]`, which has no source to read; a
//! caller check that sits in a function the rule cannot resolve by name (a trait object, a function pointer); a
//! callback named only by a string (`Promise::function_call("set_owner_cb", args, ..)`), which is not resolved to
//! the method; a callback handed a value the contract state holds, which a caller put there earlier.
//! No type information is available, so a field compared with the caller through an unrelated alias is not found.

